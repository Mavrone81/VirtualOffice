ALTER TABLE "pets_ashes_agreements"
  ADD COLUMN IF NOT EXISTS "signed_terms" JSONB,
  ADD COLUMN IF NOT EXISTS "signed_pdf_sha256" CHAR(64),
  ADD COLUMN IF NOT EXISTS "signature_version" INTEGER NOT NULL DEFAULT 0;


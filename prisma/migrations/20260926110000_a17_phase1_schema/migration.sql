ALTER TABLE "products"
  ADD COLUMN IF NOT EXISTS "required_documents" JSONB NOT NULL DEFAULT '[]',
  ADD COLUMN IF NOT EXISTS "requires_ashes_agreement" BOOLEAN NOT NULL DEFAULT false;

-- AlterTable: submission_documents — tags an uploaded file with the
-- required-document key it satisfies (G3). NULL for every existing document.
ALTER TABLE "submission_documents"
  ADD COLUMN IF NOT EXISTS "requirement_key" TEXT;

-- AlterTable: sales_transactions — the frozen commission-parties snapshot
-- (ⓢ Q33c). NEW SALES ONLY: NULL for every existing (legacy) transaction, no
